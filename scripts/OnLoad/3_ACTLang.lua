function L.t(value)
    local s = tostring(value or "")
    if L.current ~= "en" then return s end
    if M[s] then return M[s] end
    local selected = s:match("^Squadra selezionata: (.+)$")
    if selected then return "Selected Squad: " .. L.t(selected) end
    local created, database = s:match("^([%d]+) NPC creati %- Database: (.+)$")
    if created then return created .. " NPCs spawned - Database: " .. L.t(database) end
    local removed = s:match("^([%d]+) NPC rimossi entro 30 metri$")
    if removed then return removed .. " NPCs removed within 30 meters" end
    local group, roster = s:match("^(.-) %(#([%d]+, [%d]+/[%d]+) vive%)$")
    if group then return L.t(group) .. " (#" .. roster .. " alive)" end
    local point, color = s:match("^Punto ([AB]) salvato: cerchio (.+)$")
    if point then return "Point " .. point .. " saved: " .. L.t(color) .. " circle" end
    local first, second = s:match("^Battaglia avviata: ([%d]+) contro ([%d]+)$")
    if first then return "Battle started: " .. first .. " versus " .. second end
    local pending = s:match("^Rimozione guerra in corso: ([%d]+) unita$")
    if pending then return "Removing war units: " .. pending .. " remaining" end
    local crew, vehicle = s:match("^([%d]+) membri equipaggio saliti su (.+)$")
    if crew then return crew .. " crew members boarded " .. L.t(vehicle) end
    local role, faction = s:match("^(.-) non disponibile per (.+)$")
    if role then return L.t(role) .. " unavailable for " .. L.t(faction) end
    local squad, formation = s:match("^(.-): formazione (.+)$")
    if squad then return L.t(squad) .. ": formation " .. L.t(formation) end
    local troopCount, warCount = s:match("^Limite condiviso: ([%d]+) truppe ACT %+ ([%d]+) War > 24$")
    if troopCount then return "Shared limit: " .. troopCount .. " ACT troops + " .. warCount .. " War > 24" end
    local a, b = s:match("^A: ([%d]+), B: ([%d]+)$")
    if a then return "A: " .. a .. ", B: " .. b end
    local head, inner = s:match("^(.-) < (.-) >$")
    if head then return L.t(head) .. " < " .. L.t(inner) .. " >" end
    local field, state = s:match("^(.-): (ON)$")
    if not field then field, state = s:match("^(.-): (OFF)$") end
    if field then return L.t(field) .. ": " .. state end
    for _, pair in ipairs(PREFIX) do
        if s:sub(1, #pair[1]) == pair[1] then
            return pair[2] .. L.t(s:sub(#pair[1] + 1))
        end
    end
    for _, pair in ipairs(SUFFIX) do
        if s:sub(-#pair[1]) == pair[1] then
            return L.t(s:sub(1, -#pair[1] - 1)) .. pair[2]
        end
    end
    return s
end

function L.set(language)
    L.current = language == "en" and "en" or "it"
    save:set("language", L.current)
end

function L.localizeTree(node)
    if node.label then
        local original = node.label
        node.label = function()
            local text = original
            if type(original) == "function" then text = original() end
            return L.t(text)
        end
    end
    if node.header then node.header = L.t(node.header) end
    if node.action then
        local action = node.action
        node.action = function(ctx)
            local oldHint, oldToast, oldConfirm, oldAsk = ctx.hint, ctx.toast, ctx.confirm, ctx.ask
            ctx.hint = function(self, message) return oldHint(self, L.t(message)) end
            ctx.toast = function(self, message) return oldToast(self, L.t(message)) end
            ctx.confirm = function(self, message, yes, no) return oldConfirm(self, L.t(message), yes, no) end
            ctx.ask = function(self, message, submit, cancel) return oldAsk(self, L.t(message), submit, cancel) end
            return action(ctx)
        end
    end
    for _, child in ipairs(node.children or {}) do L.localizeTree(child) end
end

